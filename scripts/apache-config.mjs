// Apache 2.4 / LiteSpeed rules for a static site at the domain document root.
// TLS must reach the WHC origin directly or through a full-TLS reverse proxy.
// Never trust an arbitrary forwarding header to bypass canonical HTTPS.
const pathPattern = /^\/(?:[a-zA-Z0-9_-]+\/)*$/;
const regexEscape = value => value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const csp = "default-src 'self'; script-src 'self'; style-src 'self'; connect-src 'self'; img-src 'self'; object-src 'none'; base-uri 'none'; frame-ancestors 'none'; form-action 'self'";

export function apacheConfig({ redirects, indexing }) {
  if (!redirects || !indexing || typeof redirects !== 'object' || typeof indexing !== 'object' || Array.isArray(redirects) || Array.isArray(indexing)) throw new TypeError('Redirects and indexing must be route maps');
  for (const [from, to] of Object.entries(redirects)) {
    if (!pathPattern.test(from) || typeof to !== 'string' || !pathPattern.test(to) || from === to || Object.hasOwn(redirects, to)) throw new Error(`Invalid or chained redirect: ${from}`);
  }
  for (const [path, indexed] of Object.entries(indexing)) {
    if (!pathPattern.test(path) || typeof indexed !== 'boolean') throw new Error(`Invalid indexing entry: ${path}`);
  }
  const legacy = Object.entries(redirects).sort(([a],[b]) => a.localeCompare(b)).map(([from,to]) => {
    const relative = from.slice(1).replace(/\/$/, '');
    return `RewriteRule ^${regexEscape(relative)}${relative ? '/?' : ''}$ ${to} [R=301,END,QSD]`;
  });
  const noindex = Object.entries(indexing).filter(([,indexed]) => !indexed).map(([path]) => `SetEnvIf Request_URI "^${regexEscape(path.replace(/\/$/, ''))}/?$" site_noindex=1`);
  return `# Generated by scripts/apache-config.mjs. Apache 2.4+ / LiteSpeed.
# Deploy into the domain document root with a valid origin TLS certificate.
DirectoryIndex index.html
Options -Indexes -MultiViews
ErrorDocument 404 /404.html

AddType text/javascript .mjs
AddType image/webp .webp
AddType image/x-icon .ico

RewriteEngine On

# Deny hidden files, but permit certificate challenges under .well-known.
RewriteRule "(^|/)\\.(?!well-known(?:/|$))" - [F,END]
# The release contains only public output. These rules also protect accidental
# uploads of source folders and database/archive/editor backup files.
RewriteRule ^(?:scripts|data|node_modules|tests?|releases)(?:/|$) - [F,END,NC]
<FilesMatch "(?i)(?:^(?:indexing\\.json|redirects\\.json|_headers|_redirects|package(?:-lock)?\\.json|npm-shrinkwrap\\.json)$|\\.(?:bak|old|orig|save|swp|swo|sql|sqlite3?|db|tar|tgz|zip|7z|gz)(?:\\..*)?$|~$)">
  Require all denied
</FilesMatch>

# Permit HTTP certificate challenges before origin TLS has been issued.
RewriteRule ^\\.well-known/acme-challenge/ - [END]

# Canonicalize only the real public domain; localhost/staging hosts stay usable.
# A proxy in front of WHC must use HTTPS to the origin (not flexible HTTP mode).
RewriteCond %{HTTP_HOST} ^www\\.abortionclinic\\.ca(?::[0-9]+)?$ [NC]
RewriteRule ^ https://abortionclinic.ca%{REQUEST_URI} [R=301,END,QSD]
RewriteCond %{HTTP_HOST} ^abortionclinic\\.ca(?::[0-9]+)?$ [NC]
RewriteCond %{HTTPS} !=on
RewriteRule ^ https://abortionclinic.ca%{REQUEST_URI} [R=301,END,QSD]

# Legacy redirects are exact path matches, with or without the final slash.
# QSD drops query strings from the destination; hosting logs may still record
# the incoming request. Browsers retain URL fragments without server access.
${legacy.join('\n')}

# Ordinary files and directories keep their native static-server behavior.
# Unknown routes retain a real HTTP 404 rather than a successful SPA fallback.
RewriteCond %{REQUEST_FILENAME} -f [OR]
RewriteCond %{REQUEST_FILENAME} -d
RewriteRule ^ - [END]

Header always set Referrer-Policy "no-referrer"
Header always set X-Content-Type-Options "nosniff"
Header always set Content-Security-Policy "${csp}"
${noindex.join('\n')}
SetEnvIf Request_URI "^/404(?:\\.html|/?)$" site_noindex=1
Header always set X-Robots-Tag "noindex, follow" env=site_noindex
Header always set X-Robots-Tag "noindex, follow" env=REDIRECT_site_noindex
`;
}
